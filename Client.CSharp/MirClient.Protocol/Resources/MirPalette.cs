    /// 标准 256 色全局调色板 (RGBA 内存格式，小端序 [Byte 0: R, Byte 1: G, Byte 2: B, Byte 3: A])
    /// 盛大十周年原版官方色彩真值：RawColorArray 字节0为 Red，字节1为 Green，字节2为 Blue
    /// </summary>
    public static readonly uint[] PaletteRgba = new uint[256];

    /// <summary>
    /// 通道对调调色板 (供 F11 实时切换诊断)
    /// </summary>
    public static readonly uint[] PaletteBgra = new uint[256];

    static MirPalette()
    {
        for (int i = 0; i < 256; i++)
        {
            int offset = i * 4;
            byte c0 = RawColorArray[offset];
            byte c1 = RawColorArray[offset + 1];
            byte c2 = RawColorArray[offset + 2];
            byte a = (i == 0) ? (byte)0 : (byte)255;

            // 盛大原版官方色彩通道真值：c0 是 Red, c1 是 Green, c2 是 Blue
            // 小端序存储 [Byte 0: Red(c0), Byte 1: Green(c1), Byte 2: Blue(c2), Byte 3: a]
            PaletteRgba[i] = ((uint)a << 24) | ((uint)c2 << 16) | ((uint)c1 << 8) | c0;

            // BGR 对调模式 (供热键切换测试)
            PaletteBgra[i] = ((uint)a << 24) | ((uint)c0 << 16) | ((uint)c1 << 8) | c2;
        }
    }
